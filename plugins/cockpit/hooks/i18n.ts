const GERMAN = /^(de\b|de[-_]|german|deutsch)/i

export type LocaleInput = {
  setting: string
  // Claude Code's own `language` setting: a free string such as "german" or "de-DE"
  claudeLanguage: unknown
  env: { LC_ALL?: string | undefined; LC_MESSAGES?: string | undefined; LANG?: string | undefined }
}

export function pickLocale({ setting, claudeLanguage, env }: LocaleInput): Locale {
  if (setting === 'en' || setting === 'de') return setting
  if (typeof claudeLanguage === 'string' && claudeLanguage.trim() !== '') {
    return GERMAN.test(claudeLanguage.trim()) ? 'de' : 'en'
  }
  // The first non-empty variable decides, as in POSIX
  const value = [env.LC_ALL, env.LC_MESSAGES, env.LANG].find(v => v !== undefined && v !== '')
  return value !== undefined && /^de/i.test(value) ? 'de' : 'en'
}

export async function resolveLocale($: Eng): Promise<Locale> {
  const claudeLanguage = await $.settings.read().then(s => s['language'], () => undefined)
  const none = () => undefined
  const [LC_ALL, LC_MESSAGES, LANG] = await Promise.all([
    $.env.get('LC_ALL').catch(none),
    $.env.get('LC_MESSAGES').catch(none),
    $.env.get('LANG').catch(none),
  ])
  return pickLocale({ setting: S.cfg.settings.language, claudeLanguage, env: { LC_ALL, LC_MESSAGES, LANG } })
}
